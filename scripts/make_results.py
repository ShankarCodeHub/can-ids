"""Generate reports/RESULTS.md from saved result files ONLY (no number is typed by hand).

Every table is read from reports/results/*.csv|json. An experiment whose result
files do not exist is reported as "not run" with the reason; nothing is
estimated or filled in.

Usage:
    python scripts/make_results.py
"""

from __future__ import annotations

import json
from datetime import UTC, datetime

import pandas as pd

from canids.utils.config import load_config, resolve_path
from canids.utils.provenance import git_commit

DATA = load_config("data")
RES = resolve_path(DATA["paths"]["results"])
FIG = resolve_path(DATA["paths"]["figures"])
REPORTS = RES.parent


def md_table(df: pd.DataFrame, floatfmt: str = "{:.4f}", index: bool = False) -> str:
    """Render a DataFrame as a GitHub-markdown table (no extra dependencies)."""
    if index:
        df = df.reset_index()
    # Count columns read back as float (e.g. 14386.0) are shown as integers.
    count_cols = set()
    for c in df.columns:
        vals = pd.to_numeric(df[c], errors="coerce").dropna()
        if len(vals) and (vals % 1 == 0).all() and vals.abs().max() > 1:
            count_cols.add(c)

    def cell(v: object, col: object) -> str:
        if isinstance(v, float):
            if pd.isna(v):
                return ""
            return f"{v:,.0f}" if col in count_cols else floatfmt.format(v)
        if isinstance(v, int) and not isinstance(v, bool):
            return f"{v:,}"
        return str(v)

    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = [
        "| " + " | ".join(cell(v, c) for v, c in zip(r, df.columns, strict=True)) + " |"
        for r in df.itertuples(index=False)
    ]
    return "\n".join([head, sep, *rows])


def csv_or_none(name: str) -> pd.DataFrame | None:
    """Read a results CSV if it exists."""
    p = RES / name
    return pd.read_csv(p) if p.exists() else None


def json_or_none(name: str) -> dict | None:
    """Read a results JSON if it exists."""
    p = RES / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def fig(name: str, caption: str) -> str:
    """Markdown image link if the figure exists."""
    p = FIG / name
    return f"![{caption}](figures/{name})\n\n*{caption}*\n" if p.exists() else ""


def not_run(what: str, why: str) -> str:
    """Explicit not-run statement."""
    return f"> **Not run:** {what}. Reason: {why}\n"


def main() -> int:  # noqa: C901 - linear report assembly
    """Write reports/RESULTS.md."""
    hcrl_missing = not any(
        (resolve_path(DATA["paths"]["processed"]) / "hcrl" / "test").glob("*.parquet")
    )
    hcrl_reason = (
        "the HCRL raw files are not available on the evaluation machine "
        "(data/raw/hcrl/ is empty); the pipeline is ready and runs with the same commands."
    )
    out: list[str] = [
        "# RESULTS",
        "",
        f"Generated by `scripts/make_results.py` on {datetime.now(UTC).date()} "
        f"(git: `{git_commit()}`). Every number below is read from `reports/results/`; "
        "experiments without result files are marked **Not run**.",
        "",
    ]

    # ---------------------------------------------------------------- 1 data
    out += ["## 1. Datasets", ""]
    s = csv_or_none("dataset_summary.csv")
    if s is not None:
        out += [md_table(s, "{:,.0f}"), ""]
    if hcrl_missing:
        out += [not_run("HCRL ingestion, within-HCRL experiments and DoS evaluation", hcrl_reason)]
    out += [
        "ROAD has no DoS attack class; ROAD accelerator captures are excluded (labels not "
        "disclosed by the dataset authors).",
        "",
    ]
    b = csv_or_none("road_split_balance.csv")
    if b is not None:
        out += [
            "**ROAD splits** (ambient: chronological 60/20/20 per capture with 100-frame purge; "
            "attack captures: whole recordings `_1` train / `_2` val / `_3` test; coolant capture "
            "test-only).",
            "",
            md_table(b, "{:,.4f}"),
            "",
        ]
    lk = json_or_none("road_leakage_check.json")
    if lk:
        out += [
            f"Leakage check: **{'passed' if lk['passed'] else 'FAILED'}** on {lk['files']} files.",
            "",
        ]

    # ---------------------------------------------------------------- 2 within ROAD
    out += ["## 2. Within-dataset results: ROAD (held-out test set)", ""]
    p4 = csv_or_none("road_phase4_comparison.csv")
    if p4 is not None:
        out += [
            "### 2.1 Baseline vs Isolation Forest vs Classifier vs Hybrid",
            "",
            md_table(p4),
            "",
        ]
    m4 = json_or_none("road_phase4_test_metrics.json")
    if m4:
        out += [
            f"Test set: {m4['test_rows']:,} frames, {m4['test_attack_rows']:,} attack frames. "
            f"Hybrid thresholds: `{m4['hybrid_thresholds']}`.",
            "",
        ]
        for name, entry in m4["systems"].items():
            if "multiclass" in entry and name.startswith(("Classifier", "Hybrid (tuned)")):
                pc = pd.DataFrame(entry["multiclass"]["per_class"]).T.reset_index()
                pc = pc.rename(columns={"index": "class"})
                out += [f"**Per-class ({name})**", "", md_table(pc), ""]
    d4 = csv_or_none("road_phase4_detection_by_attack.csv")
    if d4 is not None:
        piv = d4.pivot_table(index="group", columns="system", values="detection_rate").reset_index()
        out += ["### 2.2 Detection rate by attack type", "", md_table(piv), ""]
    out += [
        fig("road_phase4_cm_hy.png", "Hybrid confusion matrix (ROAD test)"),
        fig("road_phase3_roc_pr.png", "Stage-1 ROC / PR curves (ROAD test)"),
    ]
    c3 = csv_or_none("road_phase3_fpr_by_context.csv")
    if c3 is not None:
        out += ["### 2.3 Stage-1 false-positive rate by context", "", md_table(c3, "{:.5f}"), ""]

    # ---------------------------------------------------------------- 3 cross
    out += ["## 3. Cross-dataset results", ""]
    cross = csv_or_none("cross_dataset_results.csv")
    if cross is not None:
        cj = json_or_none("cross_dataset_results.json") or {}
        out += [
            md_table(cross),
            "",
            f"Common features: `{cj.get('features')}`",
            "",
            "Dropped: " + ", ".join(f"`{k}` ({v})" for k, v in cj.get("dropped", {}).items()),
            "",
        ]
    else:
        out += [
            not_run("HCRL->ROAD and ROAD->HCRL transfer", hcrl_reason),
            "Prepared protocol (`scripts/cross_dataset.py`): common vehicle-agnostic features "
            "only (timing, window statistics, payload entropy, Hamming distance; CAN ID, payload "
            "bytes, DLC, known-ID and per-ID z-score dropped), labels {Normal, Fuzzy, Spoofing} "
            "plus binary Normal-vs-Attack, within-source reference with the same features.",
            "",
        ]

    # ---------------------------------------------------------------- 4 ablation
    out += ["## 4. Ablation (ROAD test)", ""]
    ab = csv_or_none("road_ablation.csv")
    if ab is not None:
        out += [
            "Fixed Phase 3/4 hyperparameters; each variant refit on the same seeded samples and "
            "its thresholds re-tuned on validation.",
            "",
            md_table(ab),
            "",
        ]
        abd = csv_or_none("road_ablation_by_attack.csv")
        if abd is not None:
            out += [
                md_table(
                    abd.pivot(
                        index="attack_type", columns="variant", values="detection_rate"
                    ).reset_index()
                ),
                "",
            ]
        out += [fig("road_ablation.png", "Ablation on the ROAD test set")]
    else:
        out += [not_run("ablation", "result file missing")]

    # ---------------------------------------------------------------- 5 SHAP
    out += ["## 5. Explainability (ROAD validation)", ""]
    g = csv_or_none("road_shap_global_importance.csv")
    if g is not None:
        out += ["Top-10 features by mean |SHAP| (log-odds):", "", md_table(g.head(10)), ""]
    ex = json_or_none("road_explained_alerts.json")
    if ex:
        rows = [
            {
                "case": e["case"],
                "true": e["frame"]["true_label"],
                "predicted": e["explanation"]["predicted_class"],
                "p": e["explanation"]["probability"],
                "reason": e["explanation"]["reason"],
            }
            for e in ex["examples"]
            if e["available"]
        ]
        out += [
            md_table(pd.DataFrame(rows), "{:.3f}"),
            "",
            f"SHAP backend: {ex['backend']}. {ex['note']}",
            "",
        ]
    lat = json_or_none("road_shap_latency.json")
    if lat:
        out += [
            f"Explanation latency: p50 {lat['p50_ms']:.2f} ms, p95 {lat['p95_ms']:.2f} ms, "
            f"p99 {lat['p99_ms']:.2f} ms, max {lat['max_ms']:.2f} ms (budget "
            f"{lat['budget_ms']:.0f} ms).",
            "",
        ]
    out += [fig("road_shap_global_bar.png", "Global SHAP importance")]

    # ---------------------------------------------------------------- 6 runtime
    out += ["## 6. Runtime and resources", ""]
    rb = json_or_none("road_runtime_benchmark.json")
    rt = csv_or_none("road_runtime_benchmark.csv")
    if rb and rt is not None:
        hw = rb["hardware"]
        cap = rb["can_bus_capacity_500kbps"]
        out += [
            f"Hardware: **{hw['cpu']}**, {hw['logical_cpus']} logical CPUs, {hw['ram_gb']} GB RAM, "
            f"{hw['os']}, Python {hw['python']}. Input: {rb['input']['frames']:,} frames.",
            "",
            md_table(rt, "{:,.2f}"),
            "",
            f"Feature extraction alone: {rb['features_only']['us_per_frame']:.1f} us/frame "
            f"({rb['features_only']['throughput_fps']:,.0f} frames/s).",
            "",
            f"Single SHAP explanation: p50 {rb['shap_single']['p50_ms']:.2f} ms, p95 "
            f"{rb['shap_single']['p95_ms']:.2f} ms.",
            "",
            "Model size on disk: "
            + ", ".join(f"{k} {v / 1024:,.0f} KiB" for k, v in rb["model_size_bytes"].items()),
            "",
            "CAN 500 kbit/s theoretical capacity at 100 % load: "
            f"{cap['dlc8_worst_stuffing_fps']:,.0f} (8-byte, worst-case stuffing) / "
            f"{cap['dlc8_no_stuffing_fps']:,.0f} (8-byte) / "
            f"{cap['dlc0_fps']:,.0f} (0-byte) frames/s.",
            "",
        ]
    else:
        out += [not_run("runtime benchmark", "result file missing")]
    pi = json_or_none("road_runtime_benchmark_pi4.json")
    pi_tab = csv_or_none("road_runtime_benchmark_pi4.csv")
    if pi and pi_tab is not None and rt is not None:
        hw = pi["hardware"]
        both = pd.concat([rt.assign(device="laptop"), pi_tab.assign(device="pi4")])
        out += [
            "### Raspberry Pi 4 vs laptop",
            "",
            f"Pi: {hw.get('board') or hw['cpu']}, {hw['logical_cpus']} CPUs, "
            f"{hw['ram_gb']} GB RAM, "
            f"input {pi['input']['frames']:,} frames.",
            "",
            md_table(
                both[
                    [
                        "device",
                        "scenario",
                        "frames",
                        "throughput_fps",
                        "p50_ms",
                        "p95_ms",
                        "p99_ms",
                        "cpu_percent",
                        "peak_rss_mb",
                        "peak_temp_c",
                    ]
                ],
                "{:,.2f}",
            ),
            "",
        ]
    else:
        out += [
            not_run(
                "Raspberry Pi 4 benchmark (optional Phase 8)",
                "no Raspberry Pi 4 + MCP2515 hardware was available; the edge runner, model "
                "bundle, listen-only check and setup guide are prepared in deploy/raspberry_pi/",
            ),
            "",
        ]

    # ---------------------------------------------------------------- 7 errors
    out += ["## 7. Error analysis (frozen hybrid, ROAD test)", ""]
    ea = json_or_none("road_error_analysis.json")
    if ea:
        out += [f"TP {ea['tp']:,} | FN {ea['fn']:,} | FP {ea['fp']:,}", ""]
        fa = csv_or_none("road_errors_fn_by_attack.csv")
        if fa is not None:
            out += ["**Misses by attack type**", "", md_table(fa), ""]
        out += [
            "**Miss rate by position in injection window**",
            "",
            md_table(pd.DataFrame(ea["fn_by_injection_position"])),
            "",
        ]
        fc = csv_or_none("road_errors_fp_by_capture.csv")
        if fc is not None:
            out += [
                "**False positives by capture (top 8)**",
                "",
                md_table(fc.head(8), "{:.5f}"),
                "",
            ]
        out += (
            ["**False-positive context**", ""]
            + [f"- {k}: {v}" for k, v in ea["fp_detail"].items()]
            + [""]
        )
    else:
        out += [not_run("error analysis", "result file missing")]

    # ---------------------------------------------------------------- 8 audit
    out += ["## 8. Test-set access log", ""]
    log = csv_or_none("test_access_log.csv")
    if log is not None:
        out += [
            "Every read of a test split is logged; no model or threshold was selected using "
            "test results.",
            "",
            md_table(log),
            "",
        ]
    (REPORTS / "RESULTS.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {REPORTS / 'RESULTS.md'} ({len(out)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
